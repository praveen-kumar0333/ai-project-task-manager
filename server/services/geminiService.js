const { GoogleGenAI, Type } = require('@google/genai');
const AppError = require('../utils/appError');

let currentApiKey = null;
let aiClient = null;
let isKeyRevoked = false;

/**
 * Lazily initializes and returns the Google Gemini client.
 * Returns null if GEMINI_API_KEY is missing, placeholder, or previously revoked.
 */
function getGeminiClient() {
  const apiKey = (process.env.GEMINI_API_KEY || '').trim();
  if (
    !apiKey ||
    apiKey === 'your_google_gemini_api_key_here' ||
    apiKey === 'replace_with_your_google_gemini_api_key'
  ) {
    return null;
  }

  // If the user changed or updated the key, reset the revoked status
  if (apiKey !== currentApiKey) {
    currentApiKey = apiKey;
    isKeyRevoked = false;
    aiClient = new GoogleGenAI({
      apiKey: currentApiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build'
        }
      }
    });
  }

  return aiClient;
}

/**
 * Safely extracts and parses JSON content from a Gemini response text.
 */
function parseGeminiJsonResponse(rawText) {
  if (!rawText || typeof rawText !== 'string' || rawText.trim().length === 0) {
    throw new AppError('Gemini returned an empty response', 502);
  }

  let cleaned = rawText.trim();
  if (cleaned.startsWith('```')) {
    cleaned = cleaned.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '').trim();
  }

  try {
    return JSON.parse(cleaned);
  } catch (parseError) {
    throw new AppError('Failed to parse AI-generated response as valid JSON', 502);
  }
}

/**
 * Validates and sanitizes tasks generated by the AI.
 */
function validateAndSanitizeTasks(parsedData) {
  if (!parsedData || typeof parsedData !== 'object') {
    throw new AppError('Malformed AI response: expected an object', 502);
  }

  const tasks = parsedData.tasks;
  if (!Array.isArray(tasks) || tasks.length === 0) {
    throw new AppError('AI generated an empty or missing task list', 502);
  }

  const validPriorities = ['low', 'medium', 'high'];

  return tasks.map((task, index) => {
    if (!task || typeof task !== 'object') {
      throw new AppError(`Invalid task structure at index ${index}`, 502);
    }

    const title = typeof task.title === 'string' ? task.title.trim() : '';
    const description = typeof task.description === 'string' ? task.description.trim() : '';
    const rawPriority = typeof task.priority === 'string' ? task.priority.trim().toLowerCase() : 'medium';
    const priority = validPriorities.includes(rawPriority) ? rawPriority : 'medium';

    if (!title) {
      throw new AppError(`Task at index ${index} is missing a valid title`, 502);
    }
    if (!description) {
      throw new AppError(`Task at index ${index} is missing a valid description`, 502);
    }

    return { title, description, priority };
  });
}

